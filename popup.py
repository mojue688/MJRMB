    # ========================================================
    # 倒计时
    # ========================================================

    def update_countdown(self):

        remaining = (
            self.countdown_end
            - datetime.now()
        )

        seconds = int(
            remaining.total_seconds()
        )

        # ----------------------------------------------------
        # 时间到
        # ----------------------------------------------------

        if seconds <= 0:

            self.countdown_label.config(
                text="00:00:00",
                fg=DARK_RED
            )

            return

        # ----------------------------------------------------
        # 计算
        # ----------------------------------------------------

        hours, remainder = divmod(
            seconds,
            3600
        )

        minutes, secs = divmod(
            remainder,
            60
        )

        text = (
            f"{hours:02d}:"
            f"{minutes:02d}:"
            f"{secs:02d}"
        )

        self.countdown_label.config(
            text=text
        )

        # ----------------------------------------------------
        # 一秒更新
        # ----------------------------------------------------

        self.root.after(
            1000,
            self.update_countdown
        )


