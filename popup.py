    # ========================================================
    # Ctrl + Shift + Q
    # ========================================================

    def exit_shortcut(self, event=None):

        now = time.time()

        # ----------------------------------------------------
        # 超过 2 秒重新计数
        # ----------------------------------------------------

        if (
            now
            - self.last_exit_press
            > 2
        ):

            self.exit_count = 0

        self.last_exit_press = now

        self.exit_count += 1

        log(
            "退出快捷键："
            f"{self.exit_count}/3"
        )

        # ----------------------------------------------------
        # 三次退出
        # ----------------------------------------------------

        if self.exit_count >= 3:

            log(
                "用户安全退出"
            )

            self.root.destroy()


