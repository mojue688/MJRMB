    # ========================================================
    # 五角星
    # ========================================================

    def draw_star(
        self,
        canvas,
        cx,
        cy,
        radius,
        color
    ):

        points = []

        for i in range(10):

            angle = (
                math.pi / 2
                + i * math.pi / 5
            )

            if i % 2 == 0:

                r = radius

            else:

                r = radius * 0.42

            x = (
                cx
                + r * math.cos(angle)
            )

            y = (
                cy
                - r * math.sin(angle)
            )

            points.extend(
                [x, y]
            )

        canvas.create_polygon(
            points,
            fill=color,
            outline=color
        )


